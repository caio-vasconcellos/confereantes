def translate(text: str) -> str:
    if locale.get() != "en" or not isinstance(text, str):
        return text
    if text in EN:
        return EN[text]
    for pattern, replacement in PATTERNS:
        match = re.fullmatch(pattern, text)
        if match:
            values = list(match.groups())
            if len(values) == 3:
                values[1] = {"aplicativo do banco": "banking app", "código Pix": "Pix code"}.get(values[1], values[1])
            return replacement.format(*values)
    return text


